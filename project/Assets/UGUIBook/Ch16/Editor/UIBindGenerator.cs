// 按命名规则自动生成界面的控件绑定代码。
// 用法：Project 窗口里选中界面预制体（根节点挂了 UIPanel 子类）→ 右键 › UGUIBook › 生成 UI 绑定代码。
// 生成的 Xxx.Bind.cs 放在界面脚本旁边的 Generated/ 目录，界面类需要声明为 partial。
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using TMPro;
using UnityEditor;
using UnityEngine;
using UnityEngine.UI;

namespace UGUIBook.Ch16
{
    //#region rules
    public static class UIBindGenerator
    {
        /// 命名前缀 → 控件类型。节点名以这些前缀开头，就会生成一个同名字段
        public static readonly (string Prefix, Type Type)[] Rules =
        {
            ("btn_", typeof(Button)),
            ("txt_", typeof(TMP_Text)),
            ("img_", typeof(Image)),
            ("raw_", typeof(RawImage)),
            ("tog_", typeof(Toggle)),
            ("sld_", typeof(Slider)),
            ("inp_", typeof(TMP_InputField)),
            ("dd_", typeof(TMP_Dropdown)),
            ("sr_", typeof(ScrollRect)),
            ("cg_", typeof(CanvasGroup)),
            ("rt_", typeof(RectTransform)),
            ("go_", typeof(GameObject)),
        };

        static readonly Regex s_Identifier = new Regex(@"^[A-Za-z_][A-Za-z0-9_]*$");

        struct Field
        {
            public string Name, Path;
            public Type Type;
        }
        //#endregion

        //#region menu
        const string MenuPath = "Assets/UGUIBook/生成 UI 绑定代码";

        [MenuItem(MenuPath, true)]
        static bool Validate() => Selection.gameObjects.Any(g => PrefabUtility.IsPartOfPrefabAsset(g) && g.GetComponent<UIPanel>() != null);

        [MenuItem(MenuPath, false, 2000)]
        static void GenerateSelected()
        {
            foreach (var go in Selection.gameObjects)
            {
                if (!PrefabUtility.IsPartOfPrefabAsset(go) || go.GetComponent<UIPanel>() == null) continue;
                var path = WriteFor(go, out var errors);
                foreach (var e in errors) Debug.LogError($"[UIBindGenerator] {go.name}: {e}", go);
                if (path != null) Debug.Log($"[UIBindGenerator] 已生成 {path}", go);
            }
            AssetDatabase.Refresh();
        }
        //#endregion

        //#region write
        /// 生成并写入 Generated/类名.Bind.cs。内容没变时不写文件（避免无谓的重新编译）。返回文件路径，出错返回 null
        public static string WriteFor(GameObject prefabRoot, out List<string> errors)
        {
            var panel = prefabRoot.GetComponent<UIPanel>();
            var script = MonoScript.FromMonoBehaviour(panel);
            string dir = Path.Combine(Path.GetDirectoryName(AssetDatabase.GetAssetPath(script)), "Generated");
            string code = BuildCode(prefabRoot, panel.GetType(), out errors);
            if (errors.Count > 0) return null;
            Directory.CreateDirectory(dir);
            string file = Path.Combine(dir, panel.GetType().Name + ".Bind.cs").Replace('\\', '/');
            if (!File.Exists(file) || File.ReadAllText(file) != code)
            {
                File.WriteAllText(file, code, new UTF8Encoding(false));
                Debug.LogWarning("[UIBindGenerator] 绑定代码有变化，已重写 " + file);
            }
            return file;
        }
        //#endregion

        //#region build
        public static string BuildCode(GameObject root, Type panelType, out List<string> errors)
        {
            errors = new List<string>();
            var fields = new List<Field>();
            Collect(root.transform, "", fields, errors);
            foreach (var g in fields.GroupBy(f => f.Name).Where(g => g.Count() > 1))
                errors.Add($"节点名重复：{g.Key}（{string.Join("、", g.Select(f => f.Path))}）");

            var sb = new StringBuilder();
            sb.Append("// <auto-generated>\n");
            sb.Append($"// 由 UIBindGenerator 根据 {root.name}.prefab 生成，请勿手改；预制体改动后重新生成即可。\n");
            sb.Append("// </auto-generated>\n");
            foreach (var ns in fields.Select(f => f.Type.Namespace).Distinct().OrderBy(n => n))
                sb.Append($"using {ns};\n");
            sb.Append($"\nnamespace {panelType.Namespace}\n{{\n");
            sb.Append($"    public partial class {panelType.Name}\n    {{\n");
            foreach (var f in fields) sb.Append($"        {f.Type.Name} {f.Name};\n");
            sb.Append("\n        protected override void BindUI()\n        {\n");
            foreach (var f in fields)
            {
                string call = f.Type == typeof(GameObject) ? $"BindGo(\"{f.Path}\")" : $"Bind<{f.Type.Name}>(\"{f.Path}\")";
                sb.Append($"            {f.Name} = {call};\n");
            }
            sb.Append("        }\n    }\n}\n");
            return sb.ToString();
        }

        static void Collect(Transform parent, string prefix, List<Field> fields, List<string> errors)
        {
            foreach (Transform child in parent)
            {
                string path = prefix + child.name;
                // 子节点自己也是一个界面（嵌套面板）：它的控件由它自己绑定，不往下找
                if (child.GetComponent<UIPanel>() != null) continue;
                var rule = Rules.FirstOrDefault(r => child.name.StartsWith(r.Prefix, StringComparison.Ordinal));
                if (rule.Prefix != null)
                {
                    if (!s_Identifier.IsMatch(child.name))
                        errors.Add($"{path}：名字不是合法的 C# 标识符");
                    else if (rule.Type != typeof(GameObject) && child.GetComponent(rule.Type) == null)
                        errors.Add($"{path}：前缀是 {rule.Prefix}，但节点上没有 {rule.Type.Name}");
                    else
                        fields.Add(new Field { Name = child.name, Path = path, Type = rule.Type });
                }
                Collect(child, path + "/", fields, errors);
            }
        }
        //#endregion
    }
}
